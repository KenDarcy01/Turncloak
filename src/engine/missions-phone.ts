const quizSteps = (n: number) => [
  `Every player answers the same ${n} questions on their phone. No talking, no conferring, no looking at other screens.`,
  'A question is won when at least two thirds of the players answer it correctly.',
  'When everyone has answered, the host reveals the answers one at a time. The TV shows exactly who got each one wrong.',
  'A Turncloak might miss one on purpose. Then again, so might a nervous Truecloak.',
];

const consensusSteps = (n: number) => [
  `There are ${n} questions, each with four answers. There is no right answer: pick the one you think most of the table will pick.`,
  'No talking, signals or looks until every phone has answered.',
  'A question is won when at least two thirds of the players chose the same answer.',
  'The host reveals each question in turn and the TV shows who picked what. Anyone who keeps standing out from the crowd has some explaining to do.',
];

const phoneScoring = (n: number) => ({
  success: `All ${n} questions won`,
  partial: `${Math.ceil(n / 2)} to ${n - 1} won`,
  fail: `${Math.ceil(n / 2) - 1} or fewer won`,
});

