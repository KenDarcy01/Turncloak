import type { MissionCard, PromptItem } from './missions';

/**
 * Phone games: missions everyone plays on their own phone, counted by the game
 * instead of judged by the host. Bots play these too. There are three kinds:
 *
 * - Sabotage: a crew secretly guards or sabotages the gold. Only Turncloaks can sabotage,
 *   and the TV shows how many did, never who.
 * - Quiz: everyone answers the same questions. The TV shows who got each one wrong.
 * - Consensus: everyone tries to pick the answer the rest of the table will pick.
 *
 * In each pool the first choice is the right answer (quiz) or the obvious one (consensus).
 * The choices are shuffled when they are dealt.
 */

const q = (text: string, choices: string[]): PromptItem => ({ text, answer: choices[0], choices });

