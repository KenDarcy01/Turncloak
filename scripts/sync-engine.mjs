// Copies the game engine into the edge functions folder, adding the .ts
// extensions Deno needs on relative imports.
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';

const from = 'src/engine';
const to = 'supabase/functions/_shared/engine';
mkdirSync(to, { recursive: true });
for (const f of readdirSync(from)) {
  if (!f.endsWith('.ts') || f.endsWith('.test.ts')) continue;
  const src = readFileSync(`${from}/${f}`, 'utf8').replace(/from '(\.\/[^']+)'/g, "from '$1.ts'");
  writeFileSync(`${to}/${f}`, `// Generated by scripts/sync-engine.mjs. Edit src/engine instead.\n${src}`);
}
console.log(`engine copied to ${to}`);
