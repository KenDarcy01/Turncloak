// Copies the game engine into the edge function, adding the .ts extensions
// Deno needs on relative imports. The server only needs the mission data the
// rules use (prompt pools, roles, rewards), so missions are written as a
// compact data file instead of the full cards with their on-screen text.
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { createServer } from 'vite';

const to = 'supabase/functions/game-action/engine';
mkdirSync(to, { recursive: true });
const header = '// Generated by scripts/sync-engine.mjs. Edit src/engine instead.\n';

for (const f of ['bots.ts', 'game.ts', 'types.ts', 'view.ts']) {
  const src = readFileSync(`src/engine/${f}`, 'utf8').replace(/from '(\.\/[^']+)'/g, "from '$1.ts'");
  writeFileSync(`${to}/${f}`, header + src);
}

const vite = await createServer({ server: { middlewareMode: true }, logLevel: 'silent' });
const { MISSIONS } = await vite.ssrLoadModule('/src/engine/missions.ts');
await vite.close();
const data = MISSIONS.map(({ id, pack, roles, prompts, phone, reward }) => ({
  id,
  pack: pack ?? 'castle',
  roles: roles ? { count: roles.count ?? 1 } : undefined,
  prompts,
  phone,
  reward,
}));
writeFileSync(
  `${to}/missions.ts`,
  `${header}// deno-lint-ignore-file
export type MissionPack = 'castle' | 'resort' | 'dinner';
// deno-lint-ignore no-explicit-any
export const MISSIONS: any[] = ${JSON.stringify(data)};
// deno-lint-ignore no-explicit-any
export const packOf = (m: any): MissionPack => m.pack ?? 'castle';
// deno-lint-ignore no-explicit-any
export function missionById(id: string): any {
  return MISSIONS.find((m) => m.id === id) ?? MISSIONS[0];
}
`,
);
console.log(`engine copied to ${to}`);
